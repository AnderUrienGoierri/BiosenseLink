def generate_svg_assets():
    print("======================================================================")
    print("[INIT] INICIANDO CONSTRUCCION DE LA BIBLIOTECA MASIVA DE ICONOS SVG")
    print("======================================================================\n")
    
    count = 0
    categories_created = set()
    
    for relative_path, svg_content in ICONS.items():
        full_path = os.path.join(OUTPUT_DIR, relative_path + ".svg")
        parent_dir = os.path.dirname(full_path)
        
        # Crear subcarpetas si no existen
        if not os.path.exists(parent_dir):
            os.makedirs(parent_dir, exist_ok=True)
            category_name = os.path.basename(parent_dir)
            categories_created.add(category_name)
            print(f"[DIR] Subcarpeta creada: [Icons/{category_name}]")
            
        # Escribir el archivo SVG
        try:
            with open(full_path, "w", encoding="utf-8") as f:
                f.write(svg_content)
            print(f"  [OK] Creado: Icons/{relative_path}.svg")
            count += 1
        except Exception as e:
            print(f"  [ERROR] Error escribiendo Icons/{relative_path}.svg: {e}")
            
    print("\n======================================================================")
    print(f"[SUCCESS] Biblioteca masiva compilada con exito en: {OUTPUT_DIR}")
    print(f"[SUMMARY] Resumen: {count} iconos vectoriales creados en {len(categories_created)} subcarpetas.")
    print("======================================================================")

if __name__ == "__main__":
    generate_svg_assets()
